"""Cost / latency arithmetic: Jev (measured here) vs general LLMs (published prices, vendor-reported latency).

    python scripts/cost_compare.py            # prints markdown tables

Nothing here calls any API. Jev numbers come from this repo's own rollouts. LLM prices are the
OpenRouter list prices (USD per million tokens) read from https://openrouter.ai/api/v1/models on
2026-10-02; providers and tiers vary, so treat them as +/-2x. LLM latencies are NOT measured here.
"""

import glob
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
PRICES_DATE = "2026-10-02"
JEV_INPUT_PRICE = 0.042      # USD / M input tokens, output free (vendor-published, per DataCamp's summary)
FRONTIER = {                 # my judgment of "frontier-tier" flagships, list price (in, out) USD / M tokens
    "claude-opus-5.5": (4.0, 20.0), "claude-sonnet-5.5": (2.0, 10.0), "gpt-6.1-sol": (2.0, 10.0), "grok-4.7": (2.0, 6.0)}
SMALL = {                    # cheaper / faster tier
    "gemini-3.8-flash": (0.75, 3.75), "gpt-6-luna": (0.10, 0.50), "deepseek-v4-flash": (0.028, 0.056)}
OUT_TOKENS = {"short JSON answer (no hidden reasoning)": 100, "modest reasoning + answer": 1000}
LAT_LOW, LAT_HIGH = 3.0, 30.0   # seconds: vendor-reported range for frontier LLMs (DataCamp's summary of TypeSafe's claims)
SPEED = 7.0                     # m/s cruise speed in this project


def main():
    rows = [json.loads(Path(f).read_text()) for f in glob.glob(str(ROOT / "results" / "raw" / "jev_*.json"))]
    rows = [r for r in rows if r["config"] == "jev"]
    calls = np.mean([r["jev_calls"] for r in rows])
    per_call = sum(r["cost"] for r in rows) / sum(r["jev_calls"] for r in rows)
    per_mission = np.mean([r["cost"] for r in rows])
    lat = [d["latency"] for r in rows for d in r["decisions"] if d.get("source") == "jev"]
    med, p95 = np.median(lat), np.percentile(lat, 95)
    in_tok = per_call / (JEV_INPUT_PRICE / 1e6)
    print(f"<!-- generated by scripts/cost_compare.py from {len(rows)} held-out Jev missions -->")
    print(f"Jev measured: {calls:.1f} calls/mission, ${per_call:.6f}/call, ${per_mission:.4f}/mission, "
          f"median {med*1000:.0f} ms, p95 {p95*1000:.0f} ms; implied input = {in_tok:.0f} tokens/call\n")

    def llm_cost(pin, pout, out_tok):
        return (in_tok * pin + out_tok * pout) / 1e6

    fr_in = np.mean([v[0] for v in FRONTIER.values()]); fr_out = np.mean([v[1] for v in FRONTIER.values()])
    print("| model (OpenRouter list price, in / out per M tokens) | cost per call | cost per mission | vs Jev |")
    print("|---|---|---|---|")
    print(f"| **Jev (measured)** | \${per_call:.6f} | \${per_mission:.4f} | 1x |")
    for out_label, ot in OUT_TOKENS.items():
        print(f"| *{out_label}: {ot} output tokens* | | | |")
        groups = [(f"Frontier average of 4 flagships (\\${fr_in:.2f} / \\${fr_out:.2f})", (fr_in, fr_out))]
        groups += [(f"{k} (\\${v[0]:g} / \\${v[1]:g})", v) for k, v in {**FRONTIER, **SMALL}.items()]
        for name, (pi, po) in groups:
            c = llm_cost(pi, po, ot)
            print(f"| {name} | \\${c:.5f} | \\${c * calls:.4f} | {c / per_call:.0f}x |")
    print()
    print("| decision latency | per call | decision time per mission | distance flown at 7 m/s waiting for ONE decision | speed-up vs Jev |")
    print("|---|---|---|---|---|")
    print(f"| **Jev, measured median** | {med:.2f} s | {med*calls:.0f} s | {med*SPEED:.1f} m | 1x |")
    print(f"| Jev, measured p95 | {p95:.2f} s | {p95*calls:.0f} s | {p95*SPEED:.1f} m | - |")
    print(f"| LLM, vendor-reported low end | {LAT_LOW:.0f} s | {LAT_LOW*calls:.0f} s | {LAT_LOW*SPEED:.0f} m | {LAT_LOW/med:.0f}x |")
    print(f"| LLM, vendor-reported high end | {LAT_HIGH:.0f} s | {LAT_HIGH*calls:.0f} s | {LAT_HIGH*SPEED:.0f} m | {LAT_HIGH/med:.0f}x |")


if __name__ == "__main__":
    main()
